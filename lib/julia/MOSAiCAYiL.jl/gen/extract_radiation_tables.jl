"""
    extract_radiation_tables.jl

Parse a day's `cldwtr.inp.001` and write `src/generated/cloud_liquid_optics.jl`.

    julia --project=gen -e 'include("gen/extract_radiation_tables.jl"); write_cloud_liquid_optics()'

`root` names a local tree, and defaults to the package's lazy artifact. The file is
byte-identical in all 190 day directories, so any date gives the same table.
"""

using MOSAiCAYiL: MOSAiCAYiL as MA

const OUT =
    joinpath(dirname(@__DIR__), "src", "generated", "cloud_liquid_optics.jl")

"""
    read_cldwtr(path)

`cldwtr.inp.001` as DALES's `init_cldwtr` reads it (`modradfull.f90:3036-3062`): a header of
`nsizes nbands`, the band centres, the effective radii, the water contents, then extinction,
single-scattering albedo and asymmetry as `(nsizes, nbands)` with size varying fastest.
"""
function read_cldwtr(path::AbstractString)
    lines = filter(!isempty, strip.(readlines(path)))
    length(lines) == 7 || error("Expected 7 records in $path, got $(length(lines)).")
    nsizes, nbands = parse.(Int, split(lines[1]))
    numbers(i) = parse.(Float64, split(lines[i]))

    band_centre = numbers(2)
    r_eff = numbers(3)
    water_content = numbers(4)
    length(band_centre) == nbands ||
        error("Expected $nbands band centres, got $(length(band_centre)).")
    length(r_eff) == nsizes || error("Expected $nsizes radii, got $(length(r_eff)).")
    length(water_content) == nsizes ||
        error("Expected $nsizes water contents, got $(length(water_content)).")

    grid(i) = let v = numbers(i)
        length(v) == nsizes * nbands ||
            error("Expected $(nsizes * nbands) values on record $i, got $(length(v)).")
        reshape(v, nsizes, nbands)
    end
    return (;
        nsizes,
        nbands,
        band_centre,
        r_eff,
        water_content,
        extinction = grid(5),
        single_scattering_albedo = grid(6),
        asymmetry = grid(7),
    )
end

function _print_vector(io, name, v)
    println(io, "    $name = (")
    for x in v
        println(io, "        ", repr(x), ",")
    end
    println(io, "    ),")
    return nothing
end

function _print_matrix(io, name, m)
    println(io, "    $name = [")
    for i in axes(m, 1)
        println(io, "        ", join(repr.(m[i, :]), " "), ";")
    end
    println(io, "    ],")
    return nothing
end

function write_cloud_liquid_optics(; root = MA.data_root(), date = "20200503")
    table = read_cldwtr(MA.cldwtr_inp_path(date; root))
    open(OUT, "w") do io
        println(io, "# Generated by gen/extract_radiation_tables.jl. Do not edit.")
        println(io)
        println(io, "\"\"\"")
        println(io, "The cloud-liquid optical table the AYiL radiation ran on,")
        println(io, "`cldwtr.inp.001` (`modradfull.f90:3036-3062`), byte-identical on all")
        println(io, "190 days.")
        println(io)
        println(io, "`band_centre` [cm^-1] is $(table.nbands) long; `r_eff` [μm] and")
        println(io, "`water_content` [g/m^3] are $(table.nsizes). `extinction`,")
        println(io, "`single_scattering_albedo` and `asymmetry` are")
        println(io, "`($(table.nsizes), $(table.nbands))`, size by band.")
        println(io, "\"\"\"")
        println(io, "const CLOUD_LIQUID_OPTICS = (;")
        _print_vector(io, "band_centre", table.band_centre)
        _print_vector(io, "r_eff", table.r_eff)
        _print_vector(io, "water_content", table.water_content)
        _print_matrix(io, "extinction", table.extinction)
        _print_matrix(io, "single_scattering_albedo", table.single_scattering_albedo)
        _print_matrix(io, "asymmetry", table.asymmetry)
        println(io, ")")
    end
    println(
        "wrote $OUT ($(table.nsizes) radii × $(table.nbands) bands)",
    )
    return nothing
end
