"""
    extract_day_metadata.jl

Read the `scm_in` level count and global attributes, and the first-record inversion height,
for every catalog day and write `src/generated/day_metadata.jl`.

    julia --project=gen -e 'include("gen/extract_day_metadata.jl"); write_day_metadata()'

`root` names a local tree, and defaults to the package's lazy artifact. Only the attributes
that differ between days are written; the ones that do not are constants in
`src/constants.jl`.
"""

using MOSAiCAYiL: MOSAiCAYiL as MA
using NCDatasets: NCDatasets as NC

const OUT = joinpath(dirname(@__DIR__), "src", "generated", "day_metadata.jl")

const PER_DAY_ATTRIBUTES =
    (:tskin_obs, :tskin_seaice_correction, :in_n_inucr, :in_b_inucr)

"""
    read_inversion(date, FT; root)

The inversion height [m] of a day's first LES record, by DALES's own diagnosis: the largest
centred `∂θ_l/∂z` between `INVERSION_SEARCH_MIN` and `INVERSION_SEARCH_MAX`.
"""
function read_inversion(date, ::Type{FT} = Float64; root, zmin = FT(MA.INVERSION_SEARCH_MIN), zmax = FT(MA.INVERSION_SEARCH_MAX)) where {FT}
    thl = MA.read_variable("thl", date; root, file = :profiles, translate_units = false)
    return MA.inversion_height(
        FT.(thl.data[:, 1]), FT.(thl.z),
        FT(zmin), FT(zmax),
    )
end

function read_metadata(path, ::Type{FT} = Float64) where {FT}
    NC.NCDataset(path, "r") do ds
        attrs = map(PER_DAY_ATTRIBUTES) do a
            haskey(ds.attrib, String(a)) || error("$path has no `$a` attribute")
            FT(ds.attrib[String(a)])
        end
        return (; n_levels = ds.dim["nlev"], NamedTuple{PER_DAY_ATTRIBUTES}(attrs)...)
    end
end

function emit_tuple(io, name, values)
    println(io, "    $name = (")
    for (i, v) in enumerate(values)
        println(io, "        ", repr(v), i < length(values) ? "," : "")
    end
    println(io, "    ),")
end

function write_day_metadata(::Type{FT} = Float64; root = MA.data_root()) where {FT}
    n = MA.n_cases()
    n_levels = Vector{Int}(undef, n)
    inversion = Vector{FT}(undef, n)
    cols = Dict(a => Vector{FT}(undef, n) for a in PER_DAY_ATTRIBUTES)
    for (i, d) in enumerate(MA.MOSAiCAYiL_dates)
        path = MA.scm_in_path(d; root)
        isfile(path) || error("missing $path")
        m = read_metadata(path, FT)
        n_levels[i] = m.n_levels
        for a in PER_DAY_ATTRIBUTES
            cols[a][i] = getfield(m, a)
        end
        inversion[i] = read_inversion(d, FT; root)
    end

    mkpath(dirname(OUT))
    open(OUT, "w") do io
        println(io, "# Generated by gen/extract_day_metadata.jl. Do not edit.")
        println(io, "# `scm_in` level count and the global attributes that differ by day.")
        println(io)
        println(io, "const DAY_METADATA = (;")
        emit_tuple(io, "n_levels", n_levels)
        emit_tuple(io, "inversion_height", inversion)
        for a in PER_DAY_ATTRIBUTES
            emit_tuple(io, String(a), cols[a])
        end
        println(io, ")")
    end
    println("wrote $OUT ($n days, $(length(unique(n_levels))) distinct level counts)")
    return nothing
end
