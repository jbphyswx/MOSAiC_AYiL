"""
    extract_cloud_tops.jl

Run [`MOSAiCAYiL.get_cloud_tops`](@ref) over the days a domain top is known for and write
`src/generated/cloud_tops.jl`.

    julia --project=gen -e 'include("gen/extract_cloud_tops.jl"); write_cloud_tops()'

`root` names a local tree, and defaults to the package's lazy artifact. Only the days in
`BEST_SIMULATION_TOP_F` are written: on any other day `get_cloud_tops` falls back to the
whole column
"""

using MOSAiCAYiL: MOSAiCAYiL as MA

const OUT = joinpath(dirname(@__DIR__), "src", "generated", "cloud_tops.jl")

function write_cloud_tops(::Type{FT} = Float64; root = MA.data_root(), mapper = map) where {FT}
    dates = MA.best_dates()
    (; cloud_top, failed) = MA.get_cloud_tops(dates, FT; root, mapper)

    open(OUT, "w") do io
        println(io, "# Generated by gen/extract_cloud_tops.jl. Do not edit.")
        println(io)
        println(io, "\"\"\"")
        println(io, "Cloud top [m] of each day, below its [`BEST_SIMULATION_TOP_F`](@ref).")
        println(io, "\"\"\"")
        println(io, "const CLOUD_TOP_M = Dict{String, $FT}(")
        for d in sort(collect(keys(cloud_top)))
            println(io, "    ", repr(d), " => ", repr(cloud_top[d]), ",")
        end
        println(io, ")")
        println(io)
        println(io, "\"\"\"")
        println(io, "Days whose cloud reaches the domain top, leaving no cloud top below it.")
        println(io, "\"\"\"")
        println(io, "const CLOUD_TOP_UNDETERMINED = (")
        for d in sort(failed)
            println(io, "    ", repr(d), ",")
        end
        println(io, ")")
    end
    println(
        "wrote $OUT ($(length(cloud_top)) days, $(length(failed)) undetermined: ",
        join(sort(failed), ", "), ")",
    )
    return nothing
end