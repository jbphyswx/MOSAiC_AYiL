"""
    extract_day_scalars.jl

Read `scm_in` time record 1 for every catalog day and write
`src/generated/day_scalars.jl`.

    julia --project=gen -e 'include("gen/extract_day_scalars.jl"); write_day_scalars()'

`root` names a local tree, and defaults to the package's lazy artifact. Record 2 is bitwise
identical on 190/190 days; this script does not read it.
"""

using MOSAiCAYiL: MOSAiCAYiL as MA
using NCDatasets: NCDatasets as NC

const OUT = joinpath(dirname(@__DIR__), "src", "generated", "day_scalars.jl")

function read_scalars(path)
    NC.NCDataset(path, "r") do ds
        s(name) = MA.read_variable(ds, name; file = :scm_in).data[1]
        nccn = MA.read_variable(ds, "n_ccn"; file = :scm_in).data[:, 1]
        lo, hi = extrema(nccn)
        lo == hi || error("$path n_ccn is not uniform in z: $lo … $hi")
        return (;
            lat = s("lat"),
            lon = mod(s("lon") + 180, 360) - 180,
            albedo = s("albedo"),
            albedo_snow = s("albedo_snow"),
            snow = s("snow"),
            mom_rough = s("mom_rough"),
            heat_rough = s("heat_rough"),
            sea_ice_frct = s("sea_ice_frct"),
            t_skin = s("t_skin"),
            t_skin_ocean = s("t_skin_ocean"),
            t_skin_seaice = s("t_skin_seaice"),
            open_sst = s("open_sst"),
            ps = s("ps"),
            n_ccn = lo,
        )
    end
end

function emit_ntuple(io, name, values)
    println(io, "    $name = (")
    for (i, v) in enumerate(values)
        print(io, "        ", repr(Float32(v)))
        i < length(values) && print(io, ",")
        println(io)
    end
    println(io, "    ),")
end

function write_day_scalars(; root = MA.data_root())
    n = MA.n_cases()
    fields = (
        :lat,
        :lon,
        :albedo,
        :albedo_snow,
        :snow,
        :mom_rough,
        :heat_rough,
        :sea_ice_frct,
        :t_skin,
        :t_skin_ocean,
        :t_skin_seaice,
        :open_sst,
        :ps,
        :n_ccn,
    )
    cols = Dict(f => Vector{Float32}(undef, n) for f in fields)
    for (i, d) in enumerate(MA.MOSAiCAYiL_dates)
        path = MA.scm_in_path(d; root)
        isfile(path) || error("missing $path")
        s = read_scalars(path)
        for f in fields
            cols[f][i] = Float32(getfield(s, f))
        end
    end

    mkpath(dirname(OUT))
    open(OUT, "w") do io
        println(io, "# Generated by gen/extract_day_scalars.jl. Do not edit.")
        println(io, "# scm_in time record 1; longitude wrapped to [-180, 180).")
        println(io)
        println(io, "const DAY_SCALARS = (;")
        for f in fields
            emit_ntuple(io, f, cols[f])
        end
        println(io, ")")
    end
    println("wrote $OUT ($n days)")
    return nothing
end
